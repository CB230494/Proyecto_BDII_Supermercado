/* ============================================================
   TABLAS DE PREPARACIÓN / STAGING
   ============================================================ */

CREATE TABLE STG_PRODUCTOS (
    ID_PRODUCTO   VARCHAR2(10),
    PRODUCTO      VARCHAR2(100),
    CATEGORIA     VARCHAR2(50),
    PRECIO_BASE   NUMBER(10,2)
);


CREATE TABLE STG_VENTAS (
    ID_VENTA         VARCHAR2(20),
    FECHA            VARCHAR2(20),
    ID_PRODUCTO      VARCHAR2(10),
    CANTIDAD         VARCHAR2(20),
    PRECIO_UNITARIO  VARCHAR2(20),
    SUCURSAL         VARCHAR2(100),
    METODO_PAGO      VARCHAR2(100)
);


/* ============================================================
   DIMENSIÓN PRODUCTO
   ============================================================ */

CREATE TABLE DIM_PRODUCTO (
    ID_PRODUCTO_SK NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    CODIGO_PRODUCTO VARCHAR2(10) NOT NULL,
    PRODUCTO        VARCHAR2(100) NOT NULL,
    CATEGORIA       VARCHAR2(50),
    PRECIO_BASE     NUMBER(10,2),

    CONSTRAINT UK_DIM_PRODUCTO
        UNIQUE (CODIGO_PRODUCTO)
);


/* ============================================================
   DIMENSIÓN SUCURSAL
   ============================================================ */

CREATE TABLE DIM_SUCURSAL (
    ID_SUCURSAL NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    SUCURSAL VARCHAR2(100) NOT NULL,

    CONSTRAINT UK_DIM_SUCURSAL
        UNIQUE (SUCURSAL)
);


/* ============================================================
   DIMENSIÓN MÉTODO DE PAGO
   ============================================================ */

CREATE TABLE DIM_METODO_PAGO (
    ID_METODO_PAGO NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    METODO_PAGO VARCHAR2(100) NOT NULL,

    CONSTRAINT UK_DIM_METODO_PAGO
        UNIQUE (METODO_PAGO)
);


/* ============================================================
   DIMENSIÓN TIEMPO
   ============================================================ */

CREATE TABLE DIM_TIEMPO (
    ID_TIEMPO NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    FECHA       DATE NOT NULL,
    DIA         NUMBER(2,0),
    MES         NUMBER(2,0),
    NOMBRE_MES  VARCHAR2(20),
    TRIMESTRE   VARCHAR2(2),
    ANIO        NUMBER(4,0),

    CONSTRAINT UK_DIM_TIEMPO
        UNIQUE (FECHA)
);


/* ============================================================
   TABLA DE HECHOS
   ============================================================ */

CREATE TABLE FACT_VENTAS (
    ID_FACT NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    ID_VENTA        VARCHAR2(20) NOT NULL,
    ID_TIEMPO       NUMBER NOT NULL,
    ID_PRODUCTO_SK  NUMBER NOT NULL,
    ID_SUCURSAL     NUMBER NOT NULL,
    ID_METODO_PAGO  NUMBER NOT NULL,
    CANTIDAD        NUMBER(10,0) NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    MONTO_VENTA     NUMBER(12,2) NOT NULL,

    CONSTRAINT FK_FACT_TIEMPO
        FOREIGN KEY (ID_TIEMPO)
        REFERENCES DIM_TIEMPO (ID_TIEMPO),

    CONSTRAINT FK_FACT_PRODUCTO
        FOREIGN KEY (ID_PRODUCTO_SK)
        REFERENCES DIM_PRODUCTO (ID_PRODUCTO_SK),

    CONSTRAINT FK_FACT_SUCURSAL
        FOREIGN KEY (ID_SUCURSAL)
        REFERENCES DIM_SUCURSAL (ID_SUCURSAL),

    CONSTRAINT FK_FACT_PAGO
        FOREIGN KEY (ID_METODO_PAGO)
        REFERENCES DIM_METODO_PAGO (ID_METODO_PAGO)
);